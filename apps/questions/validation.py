"""Structural and grammatical-constraint validation for questions.

Every question — seeded, written by an admin, or generated by AI — passes
through `validate_question` before it can be stored as servable.
"""
import hashlib
import re

from .checking import normalize, same
from .models import ErrorTag, QType

BLANK = re.compile(r"_{3,}")
_CYRILLIC = re.compile(r"[Ѐ-ӿ]")


class QuestionInvalid(Exception):
    def __init__(self, errors):
        self.errors = errors
        super().__init__("; ".join(errors))


def _str(value):
    return value.strip() if isinstance(value, str) else ""


def _answer_list(value, errors, label="answers", maximum=12):
    if not isinstance(value, list) or not value:
        errors.append(f"{label}: kamida bitta to'g'ri javob kerak.")
        return []
    cleaned, seen = [], set()
    for item in value[:maximum]:
        text = _str(item)
        if text and normalize(text) not in seen:
            seen.add(normalize(text))
            cleaned.append(text)
    if not cleaned:
        errors.append(f"{label}: javoblar bo'sh.")
    return cleaned


def _english(text, errors, label):
    if _CYRILLIC.search(text):
        errors.append(f"{label}: kirill harflari bo'lmasligi kerak.")


def validate_question(qtype, prompt, payload, instruction="", explanation="", difficulty=3, error_tag=ErrorTag.STRUCTURE):
    """Returns a cleaned dict of fields or raises QuestionInvalid with all problems found."""
    errors = []
    prompt, instruction, explanation = _str(prompt), _str(instruction), _str(explanation)
    payload = payload if isinstance(payload, dict) else {}
    clean = {}

    if qtype not in QType.values:
        raise QuestionInvalid(["Noma'lum savol turi."])
    if not 8 <= len(prompt) <= 700 and qtype != QType.CONSTRUCT:
        errors.append("Savol matni 8–700 belgi oralig'ida bo'lishi kerak.")
    if not isinstance(difficulty, int) or not 1 <= difficulty <= 5:
        errors.append("Qiyinlik 1 dan 5 gacha bo'lishi kerak.")
    if error_tag not in ErrorTag.values:
        errors.append("Xato toifasi noto'g'ri.")
    if not explanation:
        errors.append("O'zbekcha izoh bo'lishi shart.")

    if qtype == QType.MCQ:
        options = payload.get("options")
        correct = payload.get("correct")
        if not isinstance(options, list) or not 3 <= len(options) <= 5:
            errors.append("3–5 ta variant bo'lishi kerak.")
            options = []
        cleaned = []
        for option in options:
            text = _str(option.get("text") if isinstance(option, dict) else option)
            error = option.get("error", "") if isinstance(option, dict) else ""
            if not text:
                errors.append("Variant bo'sh bo'lmasligi kerak.")
            cleaned.append({"text": text, **({"error": error} if error in ErrorTag.values else {})})
        if len({normalize(o["text"]) for o in cleaned}) != len(cleaned):
            errors.append("Variantlar takrorlanmasligi kerak.")
        if not isinstance(correct, int) or isinstance(correct, bool) or not 0 <= correct < len(cleaned):
            errors.append("To'g'ri variant indeksi noto'g'ri.")
        clean = {"options": cleaned, "correct": correct}

    elif qtype in (QType.GAP, QType.CONTEXT):
        blanks = payload.get("blanks")
        count = len(BLANK.findall(prompt))
        if count == 0:
            errors.append("Matnda bo'sh joy (___) bo'lishi kerak.")
        if not isinstance(blanks, list) or len(blanks) != count:
            errors.append("Bo'sh joylar soni javoblar soniga mos emas.")
            blanks = []
        clean_blanks = [_answer_list(blank, errors, "blanks") for blank in blanks]
        for accepted in clean_blanks:
            for answer in accepted:
                if len(answer.split()) > 6:
                    errors.append("Bo'sh joy javobi juda uzun.")
        clean = {"blanks": clean_blanks}
        if _str(payload.get("hint")):
            clean["hint"] = _str(payload["hint"])[:120]
        if qtype == QType.CONTEXT:
            context = _str(payload.get("context"))
            if len(context) < 20:
                errors.append("Kontekst matni kamida 20 belgi bo'lishi kerak.")
            _english(context, errors, "context")
            clean["context"] = context[:1200]
        _english(prompt, errors, "prompt")

    elif qtype in (QType.TRANSFORM, QType.ERROR, QType.TRANSLATE):
        answers = _answer_list(payload.get("answers"), errors)
        clean = {"answers": answers}
        for answer in answers:
            _english(answer, errors, "answers")
        if qtype != QType.TRANSLATE:
            _english(prompt, errors, "prompt")
            if any(same(prompt, a) for a in answers):
                errors.append("To'g'ri javob savol matni bilan bir xil bo'lmasligi kerak.")
        if qtype == QType.TRANSFORM and not instruction:
            errors.append("O'zgartirish savoliga ko'rsatma kerak.")

    elif qtype == QType.CONSTRUCT:
        answers = _answer_list(payload.get("answers"), errors)
        tokens = payload.get("tokens")
        if not isinstance(tokens, list) or not 3 <= len(tokens) <= 14 or not all(_str(t) for t in tokens):
            errors.append("3–14 ta so'z bo'lagi kerak.")
            tokens = []
        tokens = [_str(t) for t in tokens]
        bag = sorted(normalize(" ".join(tokens)).split())
        for answer in answers:
            if sorted(normalize(answer).split()) != bag:
                errors.append("Har bir to'g'ri javob aynan berilgan bo'laklardan tuzilishi kerak.")
                break
        if not prompt:
            errors.append("Gap ma'nosi (o'zbekcha) ko'rsatilishi kerak.")
        clean = {"tokens": tokens, "answers": answers}

    elif qtype == QType.FREE:
        sample = _str(payload.get("sample"))
        criteria = _str(payload.get("criteria"))
        patterns = payload.get("required_patterns", [])
        if not sample:
            errors.append("Namuna javob kerak.")
        if not criteria:
            errors.append("Baholash mezoni kerak.")
        if not isinstance(patterns, list):
            patterns = []
        for pattern in patterns:
            try:
                compiled = re.compile(pattern, re.IGNORECASE)
            except (re.error, TypeError):
                errors.append("Talab qilingan qolip (regex) noto'g'ri.")
                continue
            if sample and not compiled.search(sample):
                errors.append("Namuna javob talab qilingan qolipga mos kelmaydi.")
        min_words = payload.get("min_words", 4)
        clean = {
            "sample": sample,
            "criteria": criteria[:600],
            "required_patterns": [p for p in patterns if isinstance(p, str)][:4],
            "min_words": min_words if isinstance(min_words, int) and 2 <= min_words <= 40 else 4,
        }
        if _str(payload.get("pattern_hint")):
            clean["pattern_hint"] = _str(payload["pattern_hint"])[:200]

    if errors:
        raise QuestionInvalid(errors)
    return {
        "type": qtype,
        "prompt": prompt,
        "payload": clean,
        "instruction": instruction[:240],
        "explanation": explanation,
        "difficulty": difficulty,
        "error_tag": error_tag,
    }


def content_hash(topic_id, qtype, prompt, payload):
    """Stable identity of a question's content, used to prevent duplicates."""
    if qtype == QType.MCQ:
        key = "|".join(sorted(normalize(o["text"]) for o in payload["options"]))
    elif qtype in (QType.GAP, QType.CONTEXT):
        key = normalize(payload.get("context", ""))
    elif qtype == QType.FREE:
        key = ""
    else:
        key = normalize(payload["answers"][0])
    raw = f"{topic_id}|{qtype}|{normalize(prompt)}|{key}"
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()
